interface IconProps {
  name: keyof typeof ICON_PATHS;
  className?: string;
  size?: number;
  filled?: boolean; // true = solid fill (matches how FontAwesome's "solid" style
                     // looked, e.g. the star rating widget) rather than Feather's
                     // default outline-only style. Use sparingly - outline is the
                     // intended look for nearly everything else.
}

export default function Icon({ name, className = '', size = 20, filled = false }: IconProps) {
  const path = ICON_PATHS[name];
  if (!path) {
    console.warn(`Icon "${name}" not found in ICON_PATHS`);
    return null;
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? 'currentColor' : 'none'}
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {path}
    </svg>
  );
}