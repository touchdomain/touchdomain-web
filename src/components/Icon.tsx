interface IconProps {
  name: keyof typeof ICON_PATHS;
  className?: string;
  size?: number;
  filled?: boolean; // true = solid fill (matches how FontAwesome's "solid" style
                     // looked, e.g. the star rating widget) rather than Feather's
                     // default outline-only style. Use sparingly - outline is the
                     // intended look for nearly everything else.
}

export default function Icon({ name, className = '', size = 20, filled = false }: IconProps) {
  const path = ICON_PATHS[name];
  if (!path) {
    console.warn(`Icon "${name}" not found in ICON_PATHS`);
    return null;
  }
  // strokeWidth is defined in the icon's viewBox units (24x24), so it scales
  // down proportionally with the rendered size - a strokeWidth of 2 at 20px
  // renders as a healthy ~1.7px line, but at 13-17px (used for the small
  // circular badge icons in Navigation/Footer/ContactSnippet) it thins out
  // to ~1.1-1.4px, which is genuinely hard to see, especially in a
  // screenshot or against a busy background. Scaling strokeWidth up as size
  // shrinks keeps the actual rendered thickness consistently visible
  // (targeting ~2px) regardless of how small the icon itself is.
  const effectiveStrokeWidth = Math.max(2, 2 * (24 / size));
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? 'currentColor' : 'none'}
      stroke={filled ? 'none' : 'currentColor'}
      strokeWidth={filled ? 0 : effectiveStrokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {path}
    </svg>
  );
}